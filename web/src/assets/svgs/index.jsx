export function SunburstIcon({ size = 96 }) {
  const rayCount = 16;
  return (
    <svg width={size} height={size} viewBox="0 0 100 100" fill="none" stroke="currentColor" strokeWidth="1.4" strokeLinecap="round">
      {Array.from({ length: rayCount }).map((_, i) => {
        const angle = (i / rayCount) * Math.PI * 2;
        const x1 = 50 + Math.cos(angle) * 14;
        const y1 = 50 + Math.sin(angle) * 14;
        const x2 = 50 + Math.cos(angle) * 46;
        const y2 = 50 + Math.sin(angle) * 46;
        return <line key={i} x1={x1} y1={y1} x2={x2} y2={y2} />;
      })}
    </svg>
  );
}

export function OrbitRingsIcon({ size = 96 }) {
  const rings = [46, 36, 26, 16];
  return (
    <svg width={size} height={size} viewBox="0 0 100 100" fill="none" stroke="currentColor" strokeWidth="1.4">
      {rings.map((r, i) => {
        const points = Array.from({ length: 6 })
          .map((_, p) => {
            const angle = (Math.PI / 3) * p - Math.PI / 2;
            const x = 50 + Math.cos(angle) * r;
            const y = 50 + Math.sin(angle) * r;
            return `${x},${y}`;
          })
          .join(" ");
        return <polygon key={i} points={points} />;
      })}
    </svg>
  );
}

